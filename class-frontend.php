  /** WooCommerce 3.0-3.3 submits _wpnonce; newer classic checkouts use the named field. */
  private function valid_checkout_nonce() {
    $key = isset($_POST['woocommerce-process-checkout-nonce']) ? 'woocommerce-process-checkout-nonce' : '_wpnonce';
    return isset($_POST[$key]) && is_string($_POST[$key]) && wp_verify_nonce(sanitize_text_field(wp_unslash($_POST[$key])), 'woocommerce-process_checkout');
  }

  function validate_checkout_fields(){

    // Security: Verify nonce
    $posted = WooCommerceNFe_Security::checkout_input();
    if ( $posted === false ) {
      return;
    }

    // Security: Sanitize and validate inputs (unauthenticated: arrays are treated as empty values)
    $billing_persontype = $posted['billing_persontype'] ?? 0;
    $billing_persontype = intval( $billing_persontype );

    if ($billing_persontype == 1){

      $billing_cpf = $posted['billing_cpf'] ?? '';

      if (empty( $billing_cpf )){

          wc_add_notice( sprintf( '<strong>%s</strong> %s.', esc_html__( 'CPF', 'nota-fiscal-eletronica-woocommerce' ), esc_html__( 'é um campo obrigatório', 'nota-fiscal-eletronica-woocommerce' ) ), 'error' );

      }

      if (!empty( $billing_cpf ) && !WooCommerceNFeFormat::is_cpf( $billing_cpf )){

          // Security: Use esc_html for all outputs
          wc_add_notice( 
            wp_kses( 
              sprintf( '<strong>%s</strong> %s.', 
                esc_html__( 'CPF', 'nota-fiscal-eletronica-woocommerce' ), 
                esc_html__( 'informado não é válido', 'nota-fiscal-eletronica-woocommerce' ) 
              ),
              array( 'strong' => array() )
            ), 
            'error' 
          );

      }

    }

    if ($billing_persontype == 2){

      $billing_cnpj = $posted['billing_cnpj'] ?? '';
      $billing_company = $posted['billing_company'] ?? '';

      if (empty( $billing_cnpj )){

          wc_add_notice( sprintf( '<strong>%s</strong> %s.', esc_html__( 'CNPJ', 'nota-fiscal-eletronica-woocommerce' ), esc_html__( 'é um campo obrigatório', 'nota-fiscal-eletronica-woocommerce' ) ), 'error' );

      }

      if (empty( $billing_company )){

          wc_add_notice( sprintf( '<strong>%s</strong> %s.', esc_html__( 'Razão Social', 'nota-fiscal-eletronica-woocommerce' ), esc_html__( 'é um campo obrigatório', 'nota-fiscal-eletronica-woocommerce' ) ), 'error' );

      }

      if (!empty( $billing_cnpj ) && !WooCommerceNFeFormat::is_cnpj( $billing_cnpj )){

          // Security: Use wp_kses for safe HTML output
          wc_add_notice( 
            wp_kses( 
              sprintf( '<strong>%s</strong> %s.', 
                esc_html__( 'CNPJ', 'nota-fiscal-eletronica-woocommerce' ), 
                esc_html__( 'informado não é válido', 'nota-fiscal-eletronica-woocommerce' ) 
              ),
              array( 'strong' => array() )
            ), 
            'error' 
          );

      }

    }

  }

  function validate_checkout_fields_with_plugin(){

    // Security: Verify nonce
    $posted = WooCommerceNFe_Security::checkout_input();
    if ( $posted === false ) {
      return;
    }

    $domain = '';
    $bairro = get_option('wc_settings_woocommercenfe_bairro');
    
    // Security: Sanitize input
    $billing_neighborhood = $posted['billing_neighborhood'] ?? '';

    if ($bairro == 'yes' && empty( $billing_neighborhood )){

      wc_add_notice( sprintf( '<strong>%s</strong> %s.', esc_html__( 'Bairro', 'nota-fiscal-eletronica-woocommerce' ), esc_html__( 'é um campo obrigatório', 'nota-fiscal-eletronica-woocommerce' ) ), 'error' );

    }

  }

  function localisation_address_formats( $formats ){
    // The Checkout Block formats addresses in JavaScript and cannot expand legacy placeholders.
    if (function_exists('is_checkout') && is_checkout() && function_exists('has_block') && has_block('woocommerce/checkout', (int) get_option('woocommerce_checkout_page_id'))) {
      return $formats;
    }

    $formats['BR'] = "Nome: {name}\nEndereço: {address_1}, {number}\nComplemento: {address_2}\nBairro: {neighborhood}\nCidade: {city}\nEstado: {state}\nCEP: {postcode}";
    $formats['default'] = "Nome: {name}\nEndereço: {address_1}, {number}\nComplemento: {address_2}\nBairro: {neighborhood}\nCidade: {city}\nEstado: {state}\nCEP: {postcode}";

    return $formats;

  }

  function formatted_address_replacements( $replacements, $args ) {

		// Values come from checkout/My Account posts and may be arrays; WooCommerce passes them to str_replace().
		$replacements['{number}']       = (isset($args['number']) && is_scalar($args['number'])) ? (string) $args['number'] : '';
		$replacements['{neighborhood}'] = (isset($args['neighborhood']) && is_scalar($args['neighborhood'])) ? (string) $args['neighborhood'] : '';

    return $replacements;

	}

